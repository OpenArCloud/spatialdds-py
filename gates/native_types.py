#!/usr/bin/env python3
"""The native bindings are the pinned IDL, every type of it, introspectable.

`spatialdds.dds.types` is generated by `tools/generate_types.py` from the IDL
vendored at the package's pin, and checked in. Regenerating it needs idlc,
which `gates/native_types_drift.py` runs in Docker. This gate needs only
cyclonedds, so it runs wherever the `[dds]` extra is installed, and it checks
that the checked-in tree is the right subject:

* **the era label is the pin's.** The demo's generator wrote "1.7" over 1.8
  bindings, and spatialdds_ros vendored the label;
* **one toolchain**, recorded in every generated header;
* **every type the gateway's parser reads from the vendored IDL is a generated
  class, and nothing else is.** The type identity is compared, not module
  names, because identity is what crosses the wire;
* **every generated dataclass is introspectable**: `typing.get_type_hints`
  resolves it, which the idlc output alone does not guarantee;
* **nesting does not leak**: importing the tree binds no top-level `spatial`
  package, so a program's own vendored `spatialdds_idl18` still imports beside
  it.

Usage:  gates/native_types.py
"""
from __future__ import annotations

import dataclasses
import importlib
import pkgutil
import re
import sys
import typing
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "gates"))
sys.path.insert(0, str(ROOT / "lib" / "spatialdds"))

from harness import report                                    # noqa: E402

import spatialdds as sd                                       # noqa: E402
from spatialdds.server import idlmodel, pin                   # noqa: E402

TREE = ROOT / "lib" / "spatialdds" / "spatialdds" / "dds" / "types"
IDL = pin.IDL_DIR


def idl_order() -> list[str]:
    """Every vendored IDL file, includes before includers."""
    files = sorted(p.relative_to(IDL).as_posix() for p in IDL.rglob("*.idl"))
    deps = {}
    for f in files:
        inc = re.findall(r'^#include\s+"([^"]+)"', (IDL / f).read_text(), re.M)
        deps[f] = [i for i in inc if i in files]
    out: list[str] = []

    def visit(f: str) -> None:
        if f in out:
            return
        for d in deps[f]:
            visit(d)
        out.append(f)
    for f in files:
        visit(f)
    return out


def main() -> int:
    checks: list[tuple[str, bool, str]] = []
    headers = sorted(TREE.rglob("*.py"))
    init = (TREE / "__init__.py").read_text()
    checks.append((f"the tree's label names the pin, {sd.SPEC_TAG}",
                   f"spec {sd.SPEC_TAG}." in init, init.splitlines()[3][:80]))
    versions = {m.group(1) for p in headers
                for m in [re.search(r"Cyclone DDS IDL version:\s*(\S+)",
                                    p.read_text())] if m}
    checks.append((f"one idlc toolchain across {len(headers)} generated files "
                   f"({', '.join(sorted(versions))})", len(versions) == 1,
                   f"{versions}"))

    before = set(sys.modules)
    try:
        pkg = importlib.import_module("spatialdds.dds.types")
        mods = [pkg] + [importlib.import_module(m.name) for m in
                        pkgutil.walk_packages(pkg.__path__, pkg.__name__ + ".")]
    except Exception as e:
        checks.append(("the generated tree imports", False,
                       f"{type(e).__name__}: {e}"))
        return report("native bindings", checks,
                      "the bindings are the pinned IDL, every type, "
                      "introspectable")
    leaked = sorted(m for m in set(sys.modules) - before
                    if m.split(".")[0] in ("spatial", "builtin"))
    checks.append(("importing the tree binds no top-level `spatial` or "
                   "`builtin` package", not leaked, f"{leaked[:3]}"))

    generated: dict[str, type] = {}
    for m in mods:
        for v in vars(m).values():
            name = getattr(v, "__idl_typename__", None)
            if isinstance(v, type) and name and v.__module__ == m.__name__:
                generated[name.replace("::", ".")] = v
    model = idlmodel.parse(pin.flatten(IDL, idl_order()))
    want = set(model.aggregates)
    # Structs, unions and enums: the parser counts all three as aggregates,
    # and idlc gives each a type identity.
    have = set(generated)
    checks.append((f"every one of the {len(want)} types the gateway's parser "
                   f"reads from the vendored IDL is a generated class",
                   not (want - have), f"missing {sorted(want - have)[:4]}"))
    checks.append(("and no generated type is one the IDL does not define",
                   not (have - want),
                   f"extra {sorted(have - want)[:4]}"))

    bad = []
    for name, c in sorted(generated.items()):
        if dataclasses.is_dataclass(c):
            try:
                typing.get_type_hints(c)
            except Exception as e:
                bad.append(f"{name}: {type(e).__name__}: {e}")
    checks.append((f"typing.get_type_hints resolves every generated dataclass "
                   f"({sum(dataclasses.is_dataclass(c) for c in generated.values())})",
                   not bad, "; ".join(bad[:2])))
    return report("native bindings", checks,
                  "the bindings are the pinned IDL, every type, introspectable")


if __name__ == "__main__":
    sys.exit(main())
