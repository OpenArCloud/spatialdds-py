"""The pinned type source: vendored IDL, flattened as a recording carries it.

A gateway reading a recording learns its types from the IDL the recording
embeds. A registry that starts empty has no recording, and it still has to
know the types -- to decode what is published into it, to name the instances
of a keyed resource, and to write a journal that any SpatialDDS tool can read
back. So the distribution vendors the IDL itself, at the same commit as the
generated artifacts beside it, and this module is the one place that knows how
to turn it into a model.

**Why the IDL and not the serializer tables.** The tables carry each field's
type, bound and union discriminator -- everything the JSON mapping needs --
but they do not carry `@key`. Without `@key` a keyed resource has no instance
names, so `/.../geo_anchor/v1/<key>` could not exist. The tables are a
projection of the IDL for one purpose; the IDL is the source.

**Why flattened closures rather than one blob.** An MCAP schema record holds
one self-contained translation unit, and a reader parses each record on its
own. So each publishable type gets its own flattened closure, exactly as
`tools/author_anchors.py` builds them for the fountain recording -- same
files, same order, same preamble -- which is why a journal written from a
fresh start replays through the same reader as a captured recording.

James's ruling, recorded because the alternative is tempting: there is no
"required base MCAP". A recording cosplaying as a schema file would haunt
every fresh registry forever, and the type source is the spec pin.
"""
from __future__ import annotations

import hashlib
from pathlib import Path

from . import idlmodel

#: The vendored artifacts, shared with the client half as data.
ARTIFACTS = Path(__file__).resolve().parent.parent / "artifacts"
IDL_DIR = ARTIFACTS / "idl"

#: Each publishable type with the closure of its own definition, in dependency
#: order. The same map `tools/author_anchors.py` uses to embed schemas in the
#: fountain recording, so a journal and a recording carry the same bytes for
#: the same type. Adding a publishable kind means adding its closure here and
#: vendoring whatever file it needs.
CLOSURES: dict[str, list[str]] = {
    "spatial::core::GeoAnchor": ["types.idl", "core.idl"],
    "spatial::disco::ContentAnnounce": ["types.idl", "core.idl",
                                        "discovery.idl"],
    "spatial::disco::Announce": ["types.idl", "core.idl", "discovery.idl"],
}

PREAMBLE = """// Flattened for the MCAP schema payload: includes resolved and
// preprocessor directives removed, so this is a single
// self-contained translation unit. Generated by
// tools/author_anchors.py; the authoritative sources are the
// SpatialDDS 1.8 idl/ tree.
"""


def flatten(idl_dir: Path, files: list[str]) -> str:
    """Concatenate the named IDL files with preprocessor directives stripped."""
    out = [PREAMBLE]
    for name in files:
        text = (idl_dir / name).read_text()
        body = "\n".join(l for l in text.splitlines()
                          if not l.lstrip().startswith("#"))
        out.append(f"\n// ---- {name} ----\n{body}")
    # "\n" and not "": the fountain recording was authored with this exact
    # join, and gates/fresh_start.py requires the flatten here to reproduce
    # the bytes that recording embeds. A journal and a recording have to
    # carry the same IDL for the same type or "a backup is a recording" is
    # only true of one of them.
    return "\n".join(out)


def schema_records(idl_dir: Path | None = None) -> list[tuple[str, bytes]]:
    """`(schema name, IDL bytes)` for every publishable type, or [] if absent.

    Empty rather than raising: a gateway with no type source is a legitimate
    state -- it serves an empty registry read-only and says so -- and the
    refusal belongs where publishing is switched on, in one sentence naming
    what was looked for.
    """
    d = IDL_DIR if idl_dir is None else idl_dir
    if not d.is_dir():
        return []
    missing = sorted({f for files in CLOSURES.values() for f in files
                      if not (d / f).is_file()})
    if missing:
        return []
    return [(name, flatten(d, files).encode())
            for name, files in sorted(CLOSURES.items())]


def model_from_records(records: list[tuple[str, bytes]],
                       whence: str = "") -> tuple[idlmodel.Model,
                                                  dict[str, tuple[str, bytes]]]:
    """The model, and the schema record each type was defined by.

    The second return value is what lets a published record be journalled: an
    MCAP schema record needs a name and the IDL bytes, and the truthful bytes
    are the ones this gateway itself learned the type from.

    Called with the records a recording embeds, and with the records this
    module flattens from the vendored IDL. One implementation for both, so a
    fresh registry and a seeded one cannot disagree about what a type is.
    """
    if not records:
        raise SystemExit(f"{whence or 'this type source'} carries no omgidl "
                         f"schemas, so its types cannot be read from it")
    model = idlmodel.Model()
    idl: dict[str, tuple[str, bytes]] = {}
    parsed: dict[str, idlmodel.Model] = {}
    for name, data in records:
        d = hashlib.sha256(data).hexdigest()
        if d not in parsed:
            parsed[d] = idlmodel.parse(data.decode())
        m = parsed[d]
        model.aggregates.update(m.aggregates)
        model.typedefs.update(m.typedefs)
        # A closure defines several aggregates; the one the record is named
        # for is the one a journal should register under that name.
        for fqn in m.aggregates:
            idl.setdefault(fqn, (name, data))
        own = name.replace("::", ".")
        if own in m.aggregates:
            idl[own] = (name, data)
    model._leaves = None
    return model, idl


def wire_model(idl_dir: Path | None = None):
    """The model and IDL map from the vendored pin, or `(None, {})` if absent."""
    records = schema_records(idl_dir)
    if not records:
        return None, {}
    return model_from_records(records, whence=str(IDL_DIR if idl_dir is None
                                                  else idl_dir))


def describe(idl_dir: Path | None = None) -> str:
    """One line for the banner: what the types came from."""
    d = IDL_DIR if idl_dir is None else idl_dir
    names = sorted({f for files in CLOSURES.values() for f in files})
    return (f"vendored IDL ({', '.join(names)}) under {d}"
            if schema_records(idl_dir) else
            f"none: no IDL found under {d}")
