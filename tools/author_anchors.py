#!/usr/bin/env python3
"""Author a typed SpatialDDS recording from a JSON description.

    python3 tools/author_anchors.py [--input samples/fountain-anchors.input.json]
                                    [--out samples/fountain-anchors.mcap]
                                    [--idl ../SpatialDDS-spec/idl/v1.8]

This is a deliverable rather than a build step. It is the embryo of the
"publish your own anchors" flow, and its input format is evidence for the
future write path: whatever a person can put in that file is what the types can
actually carry.

**The input is the data; this tool only serializes it.** No arithmetic, no
defaults filled in behind the author's back, no field computed from another.
Every value the recording carries appears in the input file, which is what lets
`gates/golden_anchor.py` take its expected values from the input rather than
from this code. The one thing this tool adds is the typed envelope: topic names
per §3.3.1, the embedded IDL, and the CDR encoding.

**Keep the input honest.** The input carries nothing the 1.8 types cannot
express. In particular an anchor does not reference content, because no 1.8
anchor type can: `GeoAnchor`, `AnchorEntry` and `AnchorSet` have no refs, no
assets and no `manifest_uri`. Content is positioned by its own pose and
coverage, which is the content-record model this sample succeeds, and
anchor-attached assets await the 1.9 change written up as entry 2 of
`directions/spatialdds-1.9-candidates.md`. If a future input needs a field with
no typed home, the answer is to stop, not to widen the input.

**The IDL comes from a specification checkout and ships inside the output.**
The recording embeds the flattened IDL for every type it carries, so this
repository needs no vendored IDL to serve it and a consumer needs none to read
it. That is the same bargain the retail sample makes.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from mcap.writer import Writer as McapWriter                   # noqa: E402

from spatialdds_web import idlmodel, xcdr2                     # noqa: E402

DEFAULT_IDL = ROOT.parent / "SpatialDDS-spec" / "idl" / "v1.8"
# Each schema carries the flattened closure of its own type, in dependency
# order. Mirrors how the retail sample's schemas are shaped, including the
# section markers, so the same parser reads both.
CLOSURES = {
    "spatial::core::GeoAnchor": ["types.idl", "core.idl"],
    "spatial::disco::ContentAnnounce": ["types.idl", "core.idl",
                                        "discovery.idl"],
    "spatial::disco::Announce": ["types.idl", "core.idl", "discovery.idl"],
}
PREAMBLE = """// Flattened for the MCAP schema payload: includes resolved and
// preprocessor directives removed, so this is a single
// self-contained translation unit. Generated by
// tools/author_anchors.py; the authoritative sources are the
// SpatialDDS 1.8 idl/ tree.
"""


def flatten(idl_dir: Path, files: list[str]) -> str:
    """Concatenate the named IDL files with directives stripped."""
    out = [PREAMBLE]
    for name in files:
        text = (idl_dir / name).read_text()
        body = "\n".join(l for l in text.splitlines()
                         if not l.lstrip().startswith("#"))
        out.append(f"\n// ---- {name} ----\n{body}")
    return "\n".join(out)


def time_from_iso(iso: str) -> dict:
    import calendar
    import datetime as dt
    d = dt.datetime.fromisoformat(iso.replace("Z", "+00:00"))
    if d.tzinfo is None:
        d = d.replace(tzinfo=dt.timezone.utc)
    return {"sec": calendar.timegm(d.utctimetuple()),
            "nanosec": d.microsecond * 1000}


def frame_ref(spec: dict) -> dict:
    """A FrameRef in its full 1.8 shape, guards literal."""
    return {"uuid": spec["uuid"], "fqn": spec["fqn"],
            "has_coord_convention": True, "coord_convention": "ENU",
            "has_scale": True, "scale_status": "SCALE_DECLARED",
            "meters_per_unit": 1.0, "display_unit": "m"}


def geopose(g: dict, stamp: dict, cov_row_major: list[float]) -> dict:
    return {"lat_deg": g["lat_deg"], "lon_deg": g["lon_deg"],
            "alt_m": g["alt_m"], "q": list(g["q"]), "stamp": stamp,
            "cov": {"_discriminator": "COV_POS3", "pos": cov_row_major}}


def geo_anchor(a: dict, fr: dict, stamp: dict) -> dict:
    return {
        "anchor_id": a["anchor_id"],
        "map_id": a["map_id"],
        "frame_ref": fr,
        "geopose": geopose(a["geopose"], stamp, a["cov_pos3_row_major"]),
        "method": a["method"],
        "confidence": a["confidence"],
        "checksum": "sha256:" + hashlib.sha256(
            json.dumps(a, sort_keys=True).encode()).hexdigest(),
        "cov": {"_discriminator": "COV_POS3", "pos": a["cov_pos3_row_major"]},
    }


def coverage_circle(lat: float, lon: float, alt: float, radius_m: float,
                    fr: dict) -> dict:
    """A CoverageElement in the circle form.

    The circle is used rather than a hand-computed bounding box because
    §3.3.4 says to: a producer SHOULD prefer the circle form "so consumers can
    recover the exact footprint". `bbox`/`aabb` are left absent with their
    guards false; a consumer that only understands boxes may derive one, which
    §3.3.4 explicitly permits.
    """
    return {
        "has_crs": True, "crs": "EPSG:4326",
        "has_bbox": False, "bbox": [0.0, 0.0, 0.0, 0.0],
        "has_aabb": False,
        "aabb": {"min_xyz": [0.0, 0.0, 0.0], "max_xyz": [0.0, 0.0, 0.0]},
        "global": False,
        "has_frame_ref": False, "frame_ref": fr,
        "has_coverage_window": False,
        "coverage_window_start": {"sec": 0, "nanosec": 0},
        "coverage_window_end": {"sec": 0, "nanosec": 0},
        "has_circle": True,
        "circle_center": [lon, lat, alt],
        "circle_radius_m": radius_m,
    }


def announce(svc: dict, fr: dict, stamp: dict, authority: str,
             topics: list[dict]) -> dict:
    """The service announce, with coverage the author declared.

    Its circle is a **declared** footprint: a person stated the centre and the
    radius in the input, which is the case §3.3.4 prefers the circle form for.
    Coverage the gateway computes from the resources it happens to serve is a
    different thing and uses the parameter-free enclosure instead; see the
    README.

    A recording carrying no Announce leaves a bus consumer with content and no
    discoverable service: web-complete and bus-incomplete. The recording is the
    interface, so the announce belongs in it.
    """
    c = svc["coverage_circle"]
    cov = coverage_circle(c["center_lat"], c["center_lon"], c["center_alt_m"],
                          c["radius_m"], fr)
    return {
        "service_id": svc["service_id"],
        "name": svc["name"],
        "kind": svc["kind"],
        "version": svc["version"],
        "org": svc["org"],
        "hints": [],
        "caps": {
            "supported_profiles": [
                {"name": n, "major": 1, "min_minor": 8, "max_minor": 8}
                for n in ("spatial.core", "spatial.disco")],
            "preferred_profiles": [],
            "features": ["web-binding/json"],
        },
        "topics": topics,
        "coverage": [cov],
        "coverage_frame_ref": fr,
        "has_coverage_eval_time": False,
        "coverage_eval_time": {"sec": 0, "nanosec": 0},
        "transforms": [],
        "manifest_uri": f"spatialdds://{authority}/south-mall/service/"
                        f"{svc['service_id']}",
        "auth_hint": svc.get("auth_hint", ""),
        "stamp": stamp,
        "ttl_sec": svc.get("ttl_sec", 86400),
        "coverage_source_ids": [],
    }


def topic_meta(name: str, type_seg: str, version: str) -> dict:
    """A TopicMeta row. Note it has no durability member: Appendix N.7 requires
    one on a *manifest* topic entry, and the bus type cannot carry it."""
    return {"name": name, "type": type_seg, "version": version,
            "qos_profile": "", "target_rate_hz": 0.0, "max_chunk_bytes": 0}


def content_announce(c: dict, anchor: dict, fr: dict, stamp: dict,
                     authority: str, provider: str) -> dict:
    g = anchor["geopose"]
    return {
        "content_id": c["content_id"],
        "provider_id": provider,
        "title": c["title"],
        "summary": c["summary"],
        "tags": list(c["tags"]),
        "class_id": c["class_id"],
        "manifest_uri": f"spatialdds://{authority}/south-mall/content/"
                        f"{c['content_id'].split('/')[-1]}",
        "coverage": [coverage_circle(g["lat_deg"], g["lon_deg"], g["alt_m"],
                                     c["radius_m"], fr)],
        "coverage_frame_ref": fr,
        "has_coverage_eval_time": False,
        "coverage_eval_time": {"sec": 0, "nanosec": 0},
        "transforms": [],
        "available_from": stamp,
        "available_until": {"sec": 0, "nanosec": 0},
        "stamp": stamp,
        "ttl_sec": 86400,
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--input", type=Path,
                    default=ROOT / "samples" / "fountain-anchors.input.json")
    ap.add_argument("--out", type=Path,
                    default=ROOT / "samples" / "fountain-anchors.mcap")
    ap.add_argument("--idl", type=Path, default=DEFAULT_IDL,
                    help="a SpatialDDS-spec idl/v1.8 directory")
    a = ap.parse_args()

    if not a.idl.is_dir():
        raise SystemExit(
            f"no IDL tree at {a.idl}. This tool embeds the flattened IDL in "
            f"its output, so it needs a specification checkout; point --idl at "
            f"one. Serving the result needs no IDL at all.")
    doc = json.loads(a.input.read_text())
    stamp = time_from_iso(doc["stamp_iso"])
    fr = frame_ref(doc["frame_ref"])
    domain = doc["domain"]

    schemas = {name: flatten(a.idl, files) for name, files in CLOSURES.items()}
    model = idlmodel.Model()
    for text in schemas.values():
        m = idlmodel.parse(text)
        model.aggregates.update(m.aggregates)
        model.typedefs.update(m.typedefs)
    model._leaves = None
    enc = xcdr2.Writer(model)
    dec = xcdr2.Decoder(model)

    anchors = {x["anchor_id"]: x for x in doc["anchors"]}
    anchor_topic = f"spatialdds/{domain}/frames/geo_anchor/v1"
    content_topic = f"spatialdds/{domain}/content/content_announce/v1"
    rows: list[tuple[str, str, dict]] = []
    if "service" in doc:
        # Scene-scoped, so the topic has the five segments §3.3.1 defines and
        # Appendix N.3 maps to a path. §3.3's well-known `spatialdds/discovery/
        # announce/v1` has four and therefore no N.3 path at all, which is a
        # reported finding.
        rows.append((f"spatialdds/{domain}/discovery/announce/v1",
                     "spatial::disco::Announce",
                     announce(doc["service"], fr, stamp, doc["authority"],
                              [topic_meta(anchor_topic, "geo_anchor", "v1"),
                               topic_meta(content_topic, "content_announce",
                                          "v1")])))
    for x in doc["anchors"]:
        rows.append((anchor_topic, "spatial::core::GeoAnchor",
                     geo_anchor(x, fr, stamp)))
    for c in doc["content"]:
        at = anchors[c["at_anchor"]]
        rows.append((content_topic, "spatial::disco::ContentAnnounce",
                     content_announce(c, at, fr, stamp, doc["authority"],
                                      doc["provider_id"])))

    a.out.parent.mkdir(parents=True, exist_ok=True)
    counts: dict[str, int] = {}
    with open(a.out, "wb") as fh:
        w = McapWriter(fh)
        w.start(profile="spatialdds", library="author_anchors.py")
        sch_ids, ch_ids = {}, {}
        for name, text in schemas.items():
            sch_ids[name] = w.register_schema(name=name, encoding="omgidl",
                                              data=text.encode())
        log = stamp["sec"] * 1_000_000_000 + stamp["nanosec"]
        for topic, sch_name, value in rows:
            if topic not in ch_ids:
                ch_ids[topic] = w.register_channel(
                    topic=topic, message_encoding="cdr",
                    schema_id=sch_ids[sch_name],
                    metadata={"producer": "author_anchors.py",
                              "authored": "true",
                              "spatialdds_type": sch_name.replace("::", "."),
                              "spatialdds_version": "1.8"})
            raw = enc.encode(sch_name.replace("::", "."), value)
            # Encode then decode, every sample, before it reaches the file:
            # a writer that cannot be read is worse than no writer, and this
            # is the cheapest place to find out.
            if dec.decode(sch_name.replace("::", "."), raw) != value:
                raise SystemExit(f"{sch_name}: encoded sample does not decode "
                                 f"back to the value given; refusing to write")
            seq = counts.get(topic, 0)
            w.add_message(channel_id=ch_ids[topic], log_time=log, data=raw,
                          publish_time=log, sequence=seq)
            counts[topic] = seq + 1
        w.finish()

    digest = hashlib.sha256(a.out.read_bytes()).hexdigest()
    print(f"input    {a.input}")
    print(f"idl      {a.idl}")
    print(f"out      {a.out}")
    print(f"         {a.out.stat().st_size} bytes, sha256 {digest}")
    print(f"schemas  {len(schemas)}: {', '.join(sorted(schemas))}")
    for t in sorted(counts):
        print(f"  {counts[t]:3d}  {t}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
